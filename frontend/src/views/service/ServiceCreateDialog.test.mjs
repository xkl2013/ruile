  assert.match(chat, /item\?\.id === proposal\.assistant_message_id/)
  assert.match(chat, /event\?\.proposal\?\.id === proposal\.id/)
  assert.match(chat, /type: 'service_update_proposal'/)
  assert.match(chat, /const stream = Array\.isArray\(message\.agentEventStream\)/)
  assert.match(chat, /message\.agentEventStream = stream/)
  assert.match(chat, /mergeServiceFactProposal\(existing\.proposal, proposal\)/)
  assert.match(proposalCard, /\(\) => props\.proposal\.status/)
  assert.match(proposalCard, /status\.value = nextStatus \|\| 'pending'/)
  assert.match(chatStreamHandler, /mergeServiceFactProposal/)
  assert.match(chatStreamHandler, /existing\.proposal = mergeServiceFactProposal/)
  assert.match(serviceProposalState, /resolvedServiceProposalStatuses\.has\(currentStatus\)/)
