import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import test from 'node:test'

const dialog = readFileSync(new URL('./ServiceCreateDialog.vue', import.meta.url), 'utf8')
const hub = readFileSync(new URL('./ServiceHub.vue', import.meta.url), 'utf8')
const hubState = readFileSync(new URL('./serviceHubState.ts', import.meta.url), 'utf8')
const menu = readFileSync(new URL('../../components/ServiceHubMenu.vue', import.meta.url), 'utf8')
const router = readFileSync(new URL('../../router/index.ts', import.meta.url), 'utf8')
const mobileRouter = readFileSync(new URL('../../mobile-main.ts', import.meta.url), 'utf8')
const overview = readFileSync(new URL('./ServiceOverviewView.vue', import.meta.url), 'utf8')
const activity = readFileSync(new URL('./ServiceActivityView.vue', import.meta.url), 'utf8')
const rail = readFileSync(new URL('./ServiceInfoRail.vue', import.meta.url), 'utf8')
const settings = readFileSync(new URL('./ServiceSettingsView.vue', import.meta.url), 'utf8')

test('service creation is a routed, minimal business-facing form', () => {
  assert.match(dialog, /:disabled="displayMode === 'page'"/)
  assert.match(dialog, /class="service-create-dialog-overlay"/)
  assert.match(dialog, /服务名称/)
  assert.match(dialog, /一句话说明/)
  assert.match(dialog, /submit: \[payload: \{/)
  assert.match(dialog, /description: string/)
  assert.match(hub, /view === 'create'/)
  assert.match(hub, /display-mode="page"/)
  assert.match(hub, /createServiceSpace\(\{/)
  assert.match(hub, /activate: true/)
  assert.match(router, /path: "service\/new"/)
  assert.match(router, /name: "serviceCreate"/)
})

test('service creation does not expose templates, experts, knowledge bases, or work instructions', () => {
  assert.doesNotMatch(dialog, /ServiceExpertPickerDialog/)
  assert.doesNotMatch(dialog, /ServiceKnowledgeBasePickerDialog/)
  assert.doesNotMatch(dialog, /知识库/)
  assert.doesNotMatch(dialog, /专家/)
  assert.doesNotMatch(dialog, /工作指令/)
  assert.doesNotMatch(dialog, /templateId|selectedTemplate/)
  assert.doesNotMatch(hub, /从模板创建/)
  assert.doesNotMatch(hub, /serviceTemplates|applyServiceTemplate/)
  assert.doesNotMatch(hub, /payload\.instruction|payload\.expertIds|payload\.knowledgeBaseIds/)
})

test('service cards expose customer context, activity, reminders, and direct entry', () => {
  assert.match(hub, /service\.customer\?\.familyName/)
  assert.match(hub, /service\.customer\?\.student/)
  assert.match(hub, /service\.recentActivity/)
  assert.match(hub, /openServicePageFromList\(service\.id, 'activity'\)/)
  assert.match(hub, /openServicePageFromList\(service\.id, 'reminders'\)/)
  assert.match(hub, /进入服务/)
  assert.match(hub, /更新于/)
})

test('service workspace provides history, files, reminders, activity, and the customer rail', () => {
  assert.match(hub, /class="service-hub-history-button"/)
  assert.match(hub, /历史会话/)
  assert.match(hub, /key: 'artifacts'/)
  assert.match(hub, /key: 'reminders'/)
  assert.match(hub, /openServicePage\('activity'\)/)
  assert.match(hub, /<ServiceInfoRail/)
  assert.match(hub, /当前进展/)
  assert.doesNotMatch(hub, /服务对象/)
  assert.doesNotMatch(hub, /产物摘要|当前服务还没有产物/)
  assert.match(rail, /家长与学员/)
  assert.match(rail, /最近动态/)
})

test('service sidebar keeps service rows and uses the count area for new sessions', () => {
  assert.match(menu, /class="service-hub-session-count-action"/)
  assert.match(menu, /startServiceSession\(service\.id\)/)
  assert.match(menu, /serviceHubState\.activeServiceId = serviceId/)
  assert.match(menu, /createServiceSession\(serviceId, \{ title: '新的会话' \}\)/)
  assert.doesNotMatch(menu, /if \(activeServiceId\.value === serviceId && !session\) return/)
  assert.doesNotMatch(menu, /service-hub-session-list/)
  assert.doesNotMatch(menu, /beginSessionRename|toggleSessionPinned|confirmRemoveSession/)
  assert.match(menu, /const sortedSessions/)
})

test('web service routes include overview, activity, settings, and subject compatibility redirect', () => {
  assert.match(router, /path: "service\/:serviceId\/overview"/)
  assert.match(router, /path: "service\/:serviceId\/activity"/)
  assert.match(router, /path: "service\/:serviceId\/settings\/:section\?"/)
  assert.match(router, /path: "service\/:serviceId\/subjects"/)
  assert.match(router, /redirect: \(to\) => `\/platform\/service/)
  assert.match(hub, /openServicePage\('overview'\)/)
  assert.match(hub, /openServicePage\('activity'\)/)
  assert.match(hub, /openServicePage\('settings\/basic'\)/)
})

test('mobile keeps the current service routes while web adopts the new activity route', () => {
  assert.match(mobileRouter, /path: '\/mobile\/service\/:serviceId\/overview'/)
  assert.match(mobileRouter, /path: '\/mobile\/service\/:serviceId\/subjects'/)
  assert.match(mobileRouter, /path: '\/mobile\/service\/:serviceId\/settings\/:section\?'/)
})

